import { readFileSync, writeFileSync } from 'node:fs';
const words = readFileSync('/tmp/bip39-english.txt', 'utf8').trim().split('\n').map(w => w.trim());
if (words.length !== 2048) {
  throw new Error(`Expected 2048 words, got ${words.length}`);
}
let out = '/**\n * BIP39 English wordlist (2048 words).\n * Source: https://github.com/bitcoin/bips/blob/master/bip-0039/english.txt\n * Auto-generated by scripts/gen-bip39-wordlist.mjs — do not edit by hand.\n */\n\nexport const BIP39_WORDLIST: readonly string[] = Object.freeze([\n';
for (let i = 0; i < words.length; i++) {
  out += `  '${words[i]}',`;
  if ((i + 1) % 8 === 0) out += '\n';
}
if (!out.endsWith('\n')) out += '\n';
out += ']);\n';
writeFileSync('src/crypto/bip39-wordlist.ts', out);
console.log(`Wrote src/crypto/bip39-wordlist.ts (${words.length} words)`);
